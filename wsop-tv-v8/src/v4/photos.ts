/** The file name for a person: the name without the nickname (Thomas Austin “Amarillo Slim” Preston → thomas-austin-preston). */
export const photoSlug = (name: string) => name.replace(/ [“"][^”"]+[”"]/, '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
/** Other spellings of the same person (the archive's name → the photo's name). */
const ALIAS: Record<string, string> = { 'nick-schulman': 'nicholas-schulman', 'puggy-pearson': 'walter-clyde-pearson', 'stu-ungar': 'stu-ungar' };
/** A person's WSOP.com photo, if the demo has it. */
export function photoOf(name: string): string | undefined {
  const s = photoSlug(name);
  const f = FILES.has(s) ? s : ALIAS[s];
  return f && FILES.has(f) ? `${import.meta.env.BASE_URL}hof/${f}.jpg` : undefined;
}
